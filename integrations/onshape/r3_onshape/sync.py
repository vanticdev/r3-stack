Builder = Callable[[Transport, DocumentRef, Project, StageResult], dict[str, dict[str, Any]]]
"""Models the robot in ``doc`` with standard features; returns per-part metadata
(``kind``, ``catalog_mass``, ``density``, ``material``, ``owner``, ``part_id``)."""


def camera(back: list[float], center: list[float] | None = None) -> list[float]:
    """Onshape view matrix rows (right, up, back) for a viewer along ``back``
    (identity = top view); ``center`` (m) pans the view onto that point."""
    b = np.asarray(back, dtype=float)
    b = b / np.linalg.norm(b)
    up = np.array([0.0, 0.0, 1.0]) - b[2] * b
    up = up / np.linalg.norm(up) if np.linalg.norm(up) > 1e-9 else np.array([0.0, 1.0, 0.0])
    right = np.cross(up, b)
    c = np.zeros(3) if center is None else np.asarray(center, dtype=float)
    rows = np.vstack([right, up, b])
    t = -rows @ c
    return [*rows[0], t[0], *rows[1], t[1], *rows[2], t[2]]


VIEWS = {
    "onshape_isometric.png": (camera([1.0, -1.2, 0.9]), 0.0),
    "onshape_isometric_left.png": (camera([1.0, 1.2, 0.9]), 0.0),
    "onshape_front_steering.png": (camera([0.9, -0.6, 1.0], [0.245, 0.0, 0.07]), 0.00015),
    "onshape_rear_drivetrain.png": (camera([-0.8, -1.0, 0.9], [0.02, 0.0, 0.055]), 0.00015),
    "onshape_top.png": ("top", 0.0),
}


def render_views(api: Transport, doc: DocumentRef, assembly: Any, out_dir: Path, report: SyncReport) -> None:
    """Headless shaded renders of the assembly (no browser)."""
    for filename, (view, pixel) in VIEWS.items():
        try:
            assembly.shaded_view(out_dir / filename, view, pixel_size=pixel)
            report.images.append(filename)
        except (OnshapeError, KeyError, ValueError) as error:
            report.kinematics.setdefault("render_errors", []).append(f"{filename}: {str(error)[:200]}")


def full_lock_views(assembly: Any, kinematics: dict[str, Any], out_dir: Path, report: SyncReport,
                    result: StageResult | None = None) -> None:
    horn = next((m for m in assembly.mates if m["link"].kind == "spline"), None)
    if horn is None or not kinematics.get("servo_travel_rad"):
        return
    lo, hi = kinematics["servo_travel_rad"]
    rows = kinematics.get("table", [])
    checks = []
    for label, angle in (("left", hi), ("right", lo)):
        try:
            assembly.set_mate_value(horn["feature_id"], angle)
            # Cross-check Onshape's assembly solver against the Python linkage solution.
            values = {v["featureId"]: v for v in assembly.api.json("GET", assembly.base + "/matevalues").get("mateValues", [])}
            row = min(rows, key=lambda r: abs(r["servo_rad"] - angle)) if rows else {}
            for mate in assembly.mates:
                if mate["joint"] in kinematics.get("sides", {}) and mate["feature_id"] in values:
                    onshape = float(values[mate["feature_id"]].get("rotationZ", 0.0))
                    python = row.get(mate["joint"])
                    checks.append({"servo_rad": angle, "joint": mate["joint"], "onshape_rad": onshape, "python_rad": python})
            assembly.shaded_view(out_dir / f"onshape_full_lock_{label}.png", camera([0.0, 0.0, 1.0], [0.24, 0.0, 0.06]), pixel_size=0.00025)
            report.images.append(f"onshape_full_lock_{label}.png")
            report.kinematics["onshape_solver_check"] = checks
        except (OnshapeError, KeyError) as error:
            report.kinematics.setdefault("render_errors", []).append(str(error)[:200])
    try:
        assembly.set_mate_value(horn["feature_id"], 0.0)
    except OnshapeError:
        pass
    if result is not None:
        checks = report.kinematics.get("onshape_solver_check", [])
        if not checks:
            result.add(Diagnostic.error("steering_solver_mismatch", "Onshape did not solve the steering linkage at full lock", subjects=["steering"]))
        for check in checks:
            error = abs(check["onshape_rad"] - (check["python_rad"] or 0.0))
            check["difference_deg"] = round(float(np.degrees(error)), 4)
            if check["python_rad"] is None or error > np.radians(0.5):
                result.add(Diagnostic.error("steering_solver_mismatch", f"{check['joint']}: Onshape solves {check['onshape_rad']:.4f} rad, "
                                            f"the linkage table {check['python_rad']} rad at servo {check['servo_rad']:.4f} rad",
                                            subjects=[check["joint"]], data=check))


def sync(project: Project, api: Transport, result: StageResult, builder: Builder, keep_failed: bool = False,
         attempt_label: str = "", plans: dict[str, Any] | None = None, scope: set[str] | None = None) -> SyncReport:
    from .assembly import build_assembly
    from .fit import verify_fit
    from .model import fetch_geometry
    from .motion import run_motion
    from .plan import build_plans

    spec = project.spec
    name = spec.cad.document_name or spec.robot.name
    if attempt_label:
        name = f"{name} ({attempt_label})"
    plans = plans if plans is not None else build_plans(project)
    report = SyncReport()
    reuse = os.environ.get("R3_CAD_REUSE_DOCUMENT")  # debugging: resume verification on an existing build
    doc = reuse_document(api, reuse) if reuse else create_document(api, name, spec.cad.folder)
    report.document = doc
    result.metrics["onshape_document"] = doc.url()
    ok = False
    build_dir = project.build_dir("cad")
    try:
        meta = existing_parts(api, doc, plans) if reuse else builder(api, doc, project, result, plans)  # type: ignore[call-arg]
        if not result.ok:
            return report
        model = fetch_geometry(api, doc.did, doc.wid, doc.part_studio, {n: m["part_id"] for n, m in meta.items()},
                               fixture_dir=build_dir / "fixtures")
        report.microversion = model.microversion
        report.parts = import_parts(api, doc, model, meta, build_dir / "meshes")
        verify_regeneration(project, plans, report.parts, meta, result)
        materials = {n: p.material for n, p in plans.items()}
        fit = verify_fit(project, model, materials, result)
        report.fit = fit.summary()
        report.kinematics = run_motion(project, model, fit, result)
        report.rf = antenna_position(project, model)
        assembly = build_assembly(api, doc, project, model, fit, result)
        report.assembly = assembly.verify()
        render_views(api, doc, assembly, build_dir, report)
        full_lock_views(assembly, report.kinematics, build_dir, report, result)
        ok = result.ok
        return report
    except (OnshapeError, ValueError, KeyError, AttributeError, TypeError) as error:
        result.add(Diagnostic.error("onshape_request_failed", f"{type(error).__name__}: {error}", subjects=["cad"],
                                    data={"status": getattr(error, "status", None)}))
        return report
    finally:
        keep_failed = keep_failed or os.environ.get("R3_CAD_KEEP_FAILED") == "1"
        if not ok and not keep_failed and report.document:
            try:
                delete_document(api, report.document.did)
                result.add(Diagnostic.warning("cad_attempt_deleted", f"failed CAD attempt deleted: {report.document.url()}",
                                              subjects=["cad"], data={"document_id": report.document.did}))
            except OnshapeError as error:
                result.add(Diagnostic.error("cad_attempt_delete_failed", str(error), subjects=["cad"],
                                            data={"document_id": report.document.did}))


def _json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_json_safe(v) for v in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.floating, np.integer)):
        return value.item()
    if isinstance(value, float) and not np.isfinite(value):
        return None
    return value


def write_cad_model(project: Project, report: SyncReport, api_name: str, digest: str = "") -> Path:
    from .fit import VALIDATOR_VERSION
    from .direct import GENERATOR_VERSION

    doc = report.document
    assert doc is not None
    hashes = {name: part["mesh_sha256"] for name, part in sorted(report.parts.items())}
    mesh_digest = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()[:16]
    owners = {name: part.get("owner") for name, part in report.parts.items() if part.get("kind") == "fastener"}
    model = {
        "source": {"provider": "onshape", "transport": api_name, "document_id": doc.did, "workspace_id": doc.wid,
                   "element_id": doc.part_studio, "assembly_id": report.assembly.get("element_id"), "url": doc.url(),
                   "microversion": report.microversion, "generator_digest": digest, "generator_version": GENERATOR_VERSION,
                   "validator_version": VALIDATOR_VERSION, "mesh_digest": mesh_digest, "mesh_sha256": hashes},
        "parts": report.parts,
        "fastener_owner": owners,
        "fit": report.fit,
        "kinematics": {"steering": report.kinematics},
        "rf": report.rf,
        "assembly": report.assembly,
        "images": report.images,
    }
    path = project.build_dir("cad") / "cad_model.json"
    path.write_text(json.dumps(_json_safe(model), indent=1))
    return path
