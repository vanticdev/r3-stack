import struct
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

import numpy as np

from r3_model.diagnostics import Diagnostic, StageResult
from r3_model.graph import rpy_matrix
from r3_model.project import Project

from .client import OnshapeError, Transport


@dataclass
class DocumentRef:
    did: str
    wid: str
    part_studio: str = ""
    name: str = ""

    def url(self, eid: str | None = None) -> str:
        base = f"https://cad.onshape.com/documents/{self.did}/w/{self.wid}"
        return f"{base}/e/{eid or self.part_studio}"


@dataclass
class SyncReport:
    document: DocumentRef | None = None
    feature_status: str = ""
    feature_errors: list[str] = field(default_factory=list)
    parts: dict[str, dict[str, Any]] = field(default_factory=dict)
    contacts: dict[str, Any] = field(default_factory=dict)


# --------------------------------------------------------------------- document
def create_document(api: Transport, name: str, folder: str | None) -> DocumentRef:
    body: dict[str, Any] = {"name": name, "isPublic": True,
                            "description": "Generated by R3 (r3_onshape) from robot.yaml. Do not edit by hand."}
    if folder:
        body["parentId"] = folder
    info = api.json("POST", "/documents", body=body)
    did, wid = info["id"], info["defaultWorkspace"]["id"]
    elements = api.json("GET", f"/documents/d/{did}/w/{wid}/elements")
    studio = next(e["id"] for e in elements if e.get("elementType") == "PARTSTUDIO")
    return DocumentRef(did=did, wid=wid, part_studio=studio, name=name)


def delete_document(api: Transport, did: str) -> None:
    """Move a document to the trash (recoverable from Onshape for 30 days)."""
    api.request("DELETE", f"/documents/{did}")


def find_documents(api: Transport, folder: str) -> list[dict[str, Any]]:
    listing = api.json("GET", f"/globaltreenodes/folder/{folder}")
    return [item for item in listing.get("items", []) if item.get("jsonType") == "document-summary" or item.get("resourceType") == "document"]


# ------------------------------------------------------------------ data import
def _stl_bbox_and_triangles(data: bytes) -> tuple[np.ndarray, np.ndarray, int]:
    count = struct.unpack_from("<I", data, 80)[0]
    if 84 + count * 50 != len(data):
        raise ValueError("not a binary STL")
    tri = np.frombuffer(data, dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]), count=count, offset=84)
    vertices = tri["v"].reshape(-1, 3).astype(float)
    return vertices.min(axis=0), vertices.max(axis=0), count


def tessellated_stl(api: Transport, doc: DocumentRef, part_id: str) -> bytes:
    """Binary STL (meters) built from Onshape's JSON tessellation. The binary
    STL export redirects to signed storage, which the browser-session bridge
    cannot follow, so tessellated faces are the transport-independent path."""
    data = api.json("GET", f"/partstudios/d/{doc.did}/w/{doc.wid}/e/{doc.part_studio}/tessellatedfaces",
                    query={"partId": part_id, "chordTolerance": 0.0002, "angleTolerance": 0.1, "outputFaceAppearances": False})
    triangles: list[tuple[list[float], list[list[float]]]] = []
    def point(v: Any) -> list[float]:
        return [float(v["x"]), float(v["y"]), float(v["z"])] if isinstance(v, dict) else [float(c) for c in v]

    bodies = data.get("bodies", []) if isinstance(data, dict) else data
    for body in bodies:
        for face in body.get("faces", []):
            for facet in face.get("facets", []):
                vertices = [point(v) for v in facet.get("vertices", [])]
                if len(vertices) == 3:
                    a, b, c = (np.asarray(v) for v in vertices)
                    normal = np.cross(b - a, c - a)
                    norm = float(np.linalg.norm(normal))
                    triangles.append(((normal / norm).tolist() if norm > 0 else [0.0, 0.0, 0.0], vertices))
    out = bytearray(b"R3 tessellated STL".ljust(80, b" "))
    out += struct.pack("<I", len(triangles))
    for normal, vertices in triangles:
        out += struct.pack("<12fH", *normal, *vertices[0], *vertices[1], *vertices[2], 0)
    return bytes(out)


def import_parts(api: Transport, doc: DocumentRef, project: Project, mesh_dir: Path) -> dict[str, dict[str, Any]]:
    base = f"/partstudios/d/{doc.did}/w/{doc.wid}/e/{doc.part_studio}"
    parts = api.json("GET", f"/parts/d/{doc.did}/w/{doc.wid}/e/{doc.part_studio}")
    mass = api.json("GET", f"{base}/massproperties", query={"massAsGroup": False})
    bodies = mass.get("bodies", {})
    mesh_dir.mkdir(parents=True, exist_ok=True)
    result: dict[str, dict[str, Any]] = {}
    for part in parts:
        name, pid = part.get("name", ""), part["partId"]
        props = bodies.get(pid, {})
        inertia9 = props.get("inertia", [0.0] * 9)[:9]
        tensor = np.asarray(inertia9, dtype=float).reshape(3, 3)
        stl = tessellated_stl(api, doc, pid)
        lo, hi, triangles = _stl_bbox_and_triangles(stl)
        (mesh_dir / f"{name}.stl").write_bytes(stl)
        result[name] = {
            "part_id": pid,
            "part_name": name,
            "mass": float(props.get("mass", [0.0])[0]),
            "volume": float(props.get("volume", [0.0])[0]),
            "com": [float(v) for v in props.get("centroid", [0, 0, 0])[:3]],
            "inertia": [tensor[0, 0], tensor[1, 1], tensor[2, 2], tensor[0, 1], tensor[0, 2], tensor[1, 2]],
            "bbox_min": lo.tolist(),
            "bbox_max": hi.tolist(),
            "mesh": f"meshes/{name}.stl",
            "mesh_triangles": triangles,
            "material": (part.get("material") or {}).get("displayName", ""),
            "density": float(((part.get("material") or {}).get("properties") or [{}])[0].get("value", 0) or 0)
                       if isinstance((part.get("material") or {}).get("properties"), list) else None,
        }
    return result


# ------------------------------------------------------------------ verification
def _unwrap(value: Any) -> Any:
    if isinstance(value, dict):
        return _unwrap(value["value"]) if "value" in value else value
    if isinstance(value, list):
        return [_unwrap(item) for item in value]
    return value


CONTACT_TOLERANCE = 5e-5   # parts closer than 0.05 mm are considered attached
INTERFERENCE_VOLUME = 1e-9  # 1 mm^3
TIGHT_CLEARANCE = 1.5e-3


def verify_contacts(project: Project, contacts: list[tuple[str, str, float, float]], result: StageResult) -> dict[str, Any]:
    names = set(project.spec.components)
    adjacency: dict[str, set[str]] = {name: set() for name in names}
    for a, b, distance, volume in contacts:
        if volume > INTERFERENCE_VOLUME:
            result.add(Diagnostic.error("cad_interference", f"{a} and {b} intersect by {volume * 1e9:.1f} mm^3",
                                        subjects=[a, b], data={"intersection_volume": volume}))
        if distance <= CONTACT_TOLERANCE and a in adjacency and b in adjacency:
            adjacency[a].add(b)
            adjacency[b].add(a)
        elif distance < TIGHT_CLEARANCE and volume <= INTERFERENCE_VOLUME:
            result.add(Diagnostic.warning("cad_tight_clearance", f"{a} to {b} clearance {distance * 1000:.2f} mm",
                                          subjects=[a, b], data={"distance": distance, "limit": TIGHT_CLEARANCE}))
    # Joints connect parts that need not touch in the modeled pose.
    for joint in project.spec.mechanical.joints:
        if joint.parent in adjacency and joint.child in adjacency:
            adjacency[joint.parent].add(joint.child)
            adjacency[joint.child].add(joint.parent)
    for name, neighbors in sorted(adjacency.items()):
        if not neighbors:
            result.add(Diagnostic.error("cad_part_floating", f"{name} touches no other part and has no joint",
                                        subjects=[name], hint="Add a mount, standoff or fastener so the part is physically supported."))
    root = "chassis" if "chassis" in adjacency else next(iter(adjacency))
    seen, stack = {root}, [root]
    while stack:
        for neighbor in adjacency[stack.pop()]:
            if neighbor not in seen:
                seen.add(neighbor)
                stack.append(neighbor)
    detached = sorted(names - seen)
    if detached:
        result.add(Diagnostic.error("cad_disconnected_assembly", f"parts not physically connected to {root}: {detached}",
                                    subjects=detached))
    return {"contacts": [list(c) for c in contacts], "adjacency": {k: sorted(v) for k, v in adjacency.items()}}



def expected_bbox(project: Project, cid: str) -> tuple[np.ndarray, np.ndarray]:
    """Axis-aligned envelope of a component's catalog shape at its pose."""
    comp = project.spec.components[cid]
    mech = project.catalog.component(comp.type).mechanical
    size = [float(v) for v in mech.size]
    if mech.shape == "cylinder":
        diameter, length = size
        half = {"x": [length / 2, diameter / 2, diameter / 2], "y": [diameter / 2, length / 2, diameter / 2],
                "z": [diameter / 2, diameter / 2, length]}[mech.axis]
        lo_local = -np.asarray(half) if mech.axis != "z" else np.array([-diameter / 2, -diameter / 2, 0.0])
        hi_local = np.asarray(half)
    else:
        lo_local = np.array([-size[0] / 2, -size[1] / 2, 0.0])
        hi_local = np.array([size[0] / 2, size[1] / 2, size[2]])
    corners = np.array([[x, y, z] for x in (lo_local[0], hi_local[0]) for y in (lo_local[1], hi_local[1])
                        for z in (lo_local[2], hi_local[2])])
    rotated = corners @ rpy_matrix(comp.pose.rpy).T + np.asarray(comp.pose.xyz, dtype=float)
    return rotated.min(axis=0), rotated.max(axis=0)


def verify(project: Project, parts: dict[str, dict[str, Any]], result: StageResult, meta: dict[str, dict[str, Any]],
           tolerance: float = 0.0015) -> None:
    for cid in project.spec.components:
        part = parts.get(cid)
        if part is None:
            result.add(Diagnostic.error("cad_part_missing", f"no Onshape part named {cid!r}", subjects=[cid]))
            continue
        lo, hi = expected_bbox(project, cid)
        error = float(max(np.abs(np.asarray(part["bbox_min"]) - lo).max(), np.abs(np.asarray(part["bbox_max"]) - hi).max()))
        if error > tolerance:
            result.add(Diagnostic.error("cad_envelope_mismatch", f"{cid} geometry deviates {error * 1000:.2f} mm from its catalog envelope at pose",
                                        subjects=[cid], data={"max_deviation": error, "cad_min": part["bbox_min"], "cad_max": part["bbox_max"],
                                                              "expected_min": lo.tolist(), "expected_max": hi.tolist()}))
        info = meta[cid]
        part["mass_status"] = "cad_geometry" if info["fabricated"] else "cad_catalog_density"
        if not info["fabricated"]:
            deviation = abs(part["mass"] - info["catalog_mass"]) / info["catalog_mass"]
            if deviation > 0.005:
                result.add(Diagnostic.error("cad_mass_mismatch", f"{cid} CAD mass {part['mass']:.4f} kg != catalog {info['catalog_mass']:.4f} kg",
                                            subjects=[cid], data={"cad_mass": part["mass"], "catalog_mass": info["catalog_mass"]}))
        else:
            delta = part["mass"] - info["catalog_mass"]
            result.add(Diagnostic.info("cad_mass_computed", f"{cid}: CAD mass {part['mass'] * 1000:.1f} g from geometry x {info['density']:.0f} kg/m3 "
                                       f"(catalog estimate {info['catalog_mass'] * 1000:.1f} g, delta {delta * 1000:+.1f} g)",
                                       subjects=[cid], data={"cad_mass": part["mass"], "catalog_mass": info["catalog_mass"]}))
    extra = sorted(set(parts) - set(project.spec.components))
    if extra:
        result.add(Diagnostic.error("cad_unexpected_parts", f"Onshape has parts not in robot.yaml: {extra}", subjects=extra))


# --------------------------------------------------------------------- pipeline
Builder = Callable[[Transport, DocumentRef, Project, StageResult], dict[str, dict[str, Any]]]
"""Models the robot in ``doc`` with standard features; returns per-component metadata
(``fabricated``, ``catalog_mass``, ``density``, ``material``) used by verification."""


def sync(project: Project, api: Transport, result: StageResult, builder: Builder, keep_failed: bool = False,
         attempt_label: str = "") -> SyncReport:
    spec = project.spec
    name = spec.cad.document_name or spec.robot.name
    if attempt_label:
        name = f"{name} ({attempt_label})"
    report = SyncReport()
    doc = create_document(api, name, spec.cad.folder)
    report.document = doc
    result.metrics["onshape_document"] = doc.url()
    ok = False
    try:
        meta = builder(api, doc, project, result)
        if not result.ok:
            return report
        mesh_dir = project.build_dir("cad") / "meshes"
        report.parts = import_parts(api, doc, project, mesh_dir)
        before = len(result.errors)
        verify(project, report.parts, result, meta)
        ok = len(result.errors) == before
        return report
    except (OnshapeError, ValueError, KeyError, AttributeError, TypeError) as error:
        result.add(Diagnostic.error("onshape_request_failed", str(error), subjects=["cad"], data={"status": getattr(error, "status", None)}))
        return report
    finally:
        if not ok and not keep_failed and report.document:
            try:
                delete_document(api, report.document.did)
                result.add(Diagnostic.warning("cad_attempt_deleted", f"failed CAD attempt deleted: {report.document.url()}",
                                              subjects=["cad"], data={"document_id": report.document.did}))
            except OnshapeError as error:
                result.add(Diagnostic.error("cad_attempt_delete_failed", str(error), subjects=["cad"],
                                            data={"document_id": report.document.did}))


def write_cad_model(project: Project, report: SyncReport, api_name: str) -> Path:
    doc = report.document
    assert doc is not None
    workspace = {}
    try:
        from .client import default_transport  # noqa: F401  (documented provenance only)
    except ImportError:
        pass
    model = {
        "source": {"provider": "onshape", "transport": api_name, "document_id": doc.did, "workspace_id": doc.wid,
                   "element_id": doc.part_studio, "url": doc.url(), **workspace},
        "parts": report.parts,
        "contacts": report.contacts,
    }
    path = project.build_dir("cad") / "cad_model.json"
    path.write_text(json.dumps(model, indent=2))
    return path
