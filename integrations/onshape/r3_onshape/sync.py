"""Build the robot in Onshape from scratch and import verified engineering data.

``sync(project, api, result, builder)`` creates a new document in the
configured folder and lets ``builder`` model the robot with standard Onshape
features only (see :mod:`r3_onshape.policy`). It then:

1. imports exact geometry (``bodydetails`` faces, fine tessellations) and mass
   properties, and checks that every part regenerated as planned;
2. verifies every fastener and interface, joint axes, transmission paths and
   retention on that geometry (:mod:`r3_onshape.fit`);
3. solves the steering linkage from the verified geometry and sweeps it, plus
   wheel spin (:mod:`r3_onshape.motion`);
4. builds the Assembly from the verified interfaces and checks every mate
   against its joint (:mod:`r3_onshape.assembly`);
5. renders shaded views headlessly.

A failed build deletes its document (moved to trash), so each attempt starts
from an empty folder; the passing document is pinned in ``r3.lock.yaml`` by
microversion together with hashes of the exported meshes.
"""

