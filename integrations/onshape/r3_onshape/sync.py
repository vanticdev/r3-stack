@dataclass
class DocumentRef:
    did: str
    wid: str
    part_studio: str = ""
    name: str = ""

    def url(self, eid: str | None = None) -> str:
        base = f"https://cad.onshape.com/documents/{self.did}/w/{self.wid}"
        return f"{base}/e/{eid or self.part_studio}"


@dataclass
class SyncReport:
    document: DocumentRef | None = None
    parts: dict[str, dict[str, Any]] = field(default_factory=dict)
    fit: dict[str, Any] = field(default_factory=dict)
    kinematics: dict[str, Any] = field(default_factory=dict)
    assembly: dict[str, Any] = field(default_factory=dict)
    rf: dict[str, Any] = field(default_factory=dict)
    microversion: str = ""
    images: list[str] = field(default_factory=list)


# --------------------------------------------------------------------- document
def create_document(api: Transport, name: str, folder: str | None) -> DocumentRef:
    body: dict[str, Any] = {"name": name, "isPublic": True,
                            "description": "Generated by R3 (r3_onshape direct CAD) from robot.yaml. Do not edit by hand."}
    if folder:
        body["parentId"] = folder
    info = api.json("POST", "/documents", body=body)
    did, wid = info["id"], info["defaultWorkspace"]["id"]
    elements = api.json("GET", f"/documents/d/{did}/w/{wid}/elements")
    studio = next(e["id"] for e in elements if e.get("elementType") == "PARTSTUDIO")
    for element in elements:  # new documents start with an empty "Assembly 1"
        if element.get("elementType") == "ASSEMBLY":
            api.request("DELETE", f"/elements/d/{did}/w/{wid}/e/{element['id']}")
    return DocumentRef(did=did, wid=wid, part_studio=studio, name=name)


def reuse_document(api: Transport, did: str) -> DocumentRef:
    """An existing generated document; its assemblies are removed so the
    assembly step starts clean."""
    info = api.json("GET", f"/documents/{did}")
    wid = info["defaultWorkspace"]["id"]
    elements = api.json("GET", f"/documents/d/{did}/w/{wid}/elements")
    for element in elements:
        if element.get("elementType") == "ASSEMBLY":
            api.request("DELETE", f"/elements/d/{did}/w/{wid}/e/{element['id']}")
    studio = next(e["id"] for e in elements if e.get("elementType") == "PARTSTUDIO")
    return DocumentRef(did=did, wid=wid, part_studio=studio, name=info.get("name", ""))


def existing_parts(api: Transport, doc: DocumentRef, plans: dict[str, Any]) -> dict[str, dict[str, Any]]:
    parts = api.json("GET", f"/parts/d/{doc.did}/w/{doc.wid}/e/{doc.part_studio}")
    meta = {}
    for part in parts:
        plan = plans.get(part.get("name", ""))
        if plan is not None:
            meta[plan.name] = {"kind": plan.kind, "fabricated": plan.kind != "purchased", "catalog_mass": plan.mass, "density": plan.density,
                               "material": plan.material, "owner": plan.owner, "mass_source": plan.mass_source, "part_id": part["partId"]}
    return meta


def delete_document(api: Transport, did: str) -> None:
    """Move a document to the trash (recoverable from Onshape for 30 days)."""
    api.request("DELETE", f"/documents/{did}")


def find_documents(api: Transport, folder: str) -> list[dict[str, Any]]:
    listing = api.json("GET", f"/globaltreenodes/folder/{folder}")
    return [item for item in listing.get("items", []) if item.get("jsonType") == "document-summary" or item.get("resourceType") == "document"]


# ------------------------------------------------------------------ data import
def stl_bytes(part: PartGeometry) -> bytes:
    """Binary STL (meters) of a part's welded tessellation."""
    tris = part.vertices[part.triangles]
    normals = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    lengths = np.linalg.norm(normals, axis=1, keepdims=True)
    normals = np.divide(normals, lengths, out=np.zeros_like(normals), where=lengths > 0)
    out = bytearray(b"R3 Onshape tessellation".ljust(80, b" "))
    out += struct.pack("<I", len(tris))
    for n, t in zip(normals, tris):
        out += struct.pack("<12fH", *n, *t[0], *t[1], *t[2], 0)
    return bytes(out)


def mesh_filename(name: str) -> str:
    return name.replace(":", "__") + ".stl"


def import_parts(api: Transport, doc: DocumentRef, model: GeometryModel, meta: dict[str, dict[str, Any]], mesh_dir: Path) -> dict[str, dict[str, Any]]:
    base = f"/partstudios/d/{doc.did}/w/{doc.wid}/e/{doc.part_studio}"
    mass = api.json("GET", f"{base}/massproperties", query={"massAsGroup": False, "useMassPropertyOverrides": True})
    bodies = mass.get("bodies", {})
    mesh_dir.mkdir(parents=True, exist_ok=True)
    out: dict[str, dict[str, Any]] = {}
    for name, part in model.parts.items():
        props = bodies.get(part.part_id, {})
        tensor = np.asarray(props.get("inertia", [0.0] * 9)[:9], dtype=float).reshape(3, 3)
        data = stl_bytes(part)
        filename = mesh_filename(name)
        (mesh_dir / filename).write_bytes(data)
        info = meta.get(name, {})
        out[name] = {
            "part_id": part.part_id, "part_name": name, "kind": info.get("kind"), "owner": info.get("owner"),
            "mass": float(props.get("mass", [0.0])[0]), "volume": float(props.get("volume", [0.0])[0]),
            "com": [float(v) for v in props.get("centroid", [0, 0, 0])[:3]],
            "inertia": [tensor[0, 0], tensor[1, 1], tensor[2, 2], tensor[0, 1], tensor[0, 2], tensor[1, 2]],
            "bbox_min": part.lo.tolist(), "bbox_max": part.hi.tolist(), "mesh": f"meshes/{filename}",
            "mesh_triangles": int(len(part.triangles)), "mesh_sha256": hashlib.sha256(data).hexdigest(),
            "material": info.get("material", ""), "density": info.get("density"),
            "mass_status": "catalog_override" if info.get("kind") == "purchased" else "cad_geometry",
        }
    return out


def verify_regeneration(project: Project, plans: dict[str, Any], parts: dict[str, dict[str, Any]], meta: dict[str, dict[str, Any]],
                        result: StageResult, tolerance: float = 5e-5) -> None:
    """Every planned part exists, regenerated to its planned shape (bounding box
    and volume of the local plan solid) and carries the right mass source."""
    from .geometry import plan_manifold

    for name, plan in plans.items():
        part = parts.get(name)
        if part is None:
            result.add(Diagnostic.error("cad_part_missing", f"no Onshape part named {name!r}", subjects=[name]))
            continue
        solid = plan_manifold(plan)
        box = np.asarray(solid.bounding_box()).reshape(2, 3)
        deviation = float(max(np.abs(np.asarray(part["bbox_min"]) - box[0]).max(), np.abs(np.asarray(part["bbox_max"]) - box[1]).max()))
        if deviation > tolerance:
            result.add(Diagnostic.error("cad_regeneration_mismatch", f"{name}: Onshape geometry deviates {deviation * 1e3:.3f} mm from its plan",
                                        subjects=[name], data={"deviation": deviation, "cad_min": part["bbox_min"], "cad_max": part["bbox_max"],
                                                               "plan_min": box[0].tolist(), "plan_max": box[1].tolist()}))
        info = meta.get(name, {})
        if plan.mass is not None:
            if abs(part["mass"] - plan.mass) > 0.005 * plan.mass:
                result.add(Diagnostic.error("cad_mass_mismatch", f"{name}: CAD mass {part['mass']:.5f} kg != catalog {plan.mass:.5f} kg",
                                            subjects=[name], data={"cad_mass": part["mass"], "catalog_mass": plan.mass}))
        elif part["mass"] <= 0:
            result.add(Diagnostic.error("cad_mass_mismatch", f"{name}: fabricated part has no mass (material missing)", subjects=[name]))
        del info
    extra = sorted(set(parts) - set(plans))
    if extra:
        result.add(Diagnostic.error("cad_unexpected_parts", f"Onshape has parts not in the plan: {extra}", subjects=extra))


def antenna_position(project: Project, model: GeometryModel) -> dict[str, Any]:
    """Feed point of the receiver antenna (center of its dipole) and its height
    above the receiver's mounting face, derived from the CAD geometry."""
    spec = project.spec
    antenna = next((cid for cid, c in spec.components.items() if project.catalog.component(c.type).kind == "antenna"), None)
    receiver = next((cid for cid, c in spec.components.items() if project.catalog.component(c.type).kind == "radio"), None)
    if antenna is None or antenna not in model.parts or receiver not in model.parts:
        return {}
    part = model[antenna]
    dipoles = [f for f in part.faces_of("CYLINDER") if abs(float(f.direction @ np.array([0.0, 0.0, 1.0]))) < 1e-6]
    if dipoles:
        face = max(dipoles, key=lambda f: float(np.ptp(f.triangles.reshape(-1, 3) @ f.direction)) if f.triangles is not None else 0.0)
        pts = face.triangles.reshape(-1, 3)
        t = (pts - face.origin) @ face.direction
        feed = face.origin + face.direction * (t.min() + t.max()) / 2
    else:
        feed = (part.lo + part.hi) / 2
    mount_z = float(model[receiver].lo[2])
    return {"antenna_component": antenna, "receiver": receiver, "antenna_position": feed.tolist(),
            "antenna_height_above_mount": float(feed[2] - mount_z), "mount_z": mount_z}


