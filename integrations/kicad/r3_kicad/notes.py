"""Design notes for the carrier HAT, generated from the design data and KiCad's results."""

from __future__ import annotations

from typing import Any

from . import ipc2152
from .arbiter import ArbiterParams
from .intent import BoardIntent
from .regulators import BuckDesign, design_notes_markdown, hold_up_time


def design_notes(intent: BoardIntent, pi: BuckDesign, servo: BuckDesign, power: dict[str, Any],
                 erc: dict[str, Any], drc: dict[str, Any]) -> str:
    dt = float(intent.rules.get("delta_t_power", 20.0))
    arb = ArbiterParams()
    hold = hold_up_time(pi.values["c_out_effective"], pi.values["v_out_nominal"], 4.63, 6.5)
    lines = [
        f"# {intent.title}: design notes",
        "",
        "Generated by `r3_kicad` from the design intent (`carrier_hat.py`) and KiCad's own outputs; do not edit by hand.",
        "",
        "## How the board was made",
        "",
        "Everything ran headless (no KiCad window, as on a server); the flow is `python -m r3_kicad.flow <board dir>`.",
        "",
        "- Schematic: official KiCad library symbols placed with `kicad-sch-api` (KiCad 10 has no headless schematic "
        "API; `kicad-cli sch` only checks and exports), a net label on every connected pin, no-connect flags on unused "
        "pins; normalized by `kicad-cli sch upgrade`, checked by `kicad-cli sch erc` and by comparing KiCad's own "
        "netlist export with the design intent.",
        "- Board: KiCad's `pcbnew` Python module (KiCad's bundled interpreter) applies Board Setup (net classes, "
        "rules, sizes), the HAT outline, Update PCB from Schematic (official library footprints linked to their "
        "symbols, pad nets from the netlist), placement, and the hand-routed power copper (locked tracks and vias).",
        "- Signals: Specctra DSN export from pcbnew, Freerouting CLI (headless JVM), SES import; then GND pours on "
        "both layers and Fill All Zones in pcbnew. DRC, schematic parity and all outputs by `kicad-cli`.",
        f"- ERC: {erc.get('errors')} errors, {erc.get('warnings')} warnings. DRC: {drc.get('errors')} errors, "
        f"{drc.get('unconnected')} unconnected, {drc.get('parity')} schematic-parity issues, {drc.get('warnings')} warnings.",
        "",
        "## Board",
        "",
        f"- {intent.width:g} x {intent.height:g} mm, R{intent.corner_radius:g} corners, {intent.thickness:g} mm FR-4, 2 layers, "
        f"{intent.copper_oz:g} oz copper. Rules for a standard 2-layer fab (JLCPCB/PCBWay): min track/clearance "
        f"{intent.rules['min_track_width']}/{intent.rules['min_clearance']} mm, via {intent.rules['min_via_diameter']}/"
        f"{intent.rules['min_via_drill']} mm, copper-edge {intent.rules['copper_edge_clearance']} mm.",
        "- 2x20 socket on the bottom side at the HAT position; GND pours on both layers; power rails as wide "
        "hand-routed tracks (the 5 V path to the Pi pins doubled on the bottom layer).",
        "",
        "## Copper sizing (IPC-2152)",
        "",
        f"External-conductor fit (Brooks, PCD&F 2015): dT = 215.3 I^2 W^-1.15 Th^-1 (mil, A, C), 1 oz = 1.35 mil. "
        f"Power copper sized for {dt:g} C rise, signals for 10 C; no plane modifier (conservative).",
        "",
        "| Current | Width at 10 C | Width at 20 C |",
        "| --- | --- | --- |",
    ]
    for current in (0.2, 1.0, 3.0, 5.0):
        lines.append(f"| {current:g} A | {ipc2152.required_width(current, intent.copper_oz, 10):.2f} mm | "
                     f"{ipc2152.required_width(current, intent.copper_oz, 20):.2f} mm |")
    lines += ["", "| Net | Design current | Pour area (mm^2) | Vias (capacity) | Narrowest hand-routed track |",
              "| --- | --- | --- | --- | --- |"]
    for net, e in power.items():
        pours = ", ".join(f"{k} {v:g}" for k, v in e["pour_area_mm2"].items()) or "-"
        track = (f"{e['narrowest_deliberate_width'] * 1000:.2f} mm ({e['narrowest_deliberate_rating']:.2f} A)"
                 if "narrowest_deliberate_width" in e else "-")
        lines.append(f"| {net} | {e['design_current']:g} A | {pours} | {e['vias']} ({e['via_capacity']:g} A) | {track} |")
    lines += [
        "",
        "The Pi's 5 V pins (2, 4) sit on the header's edge row, behind pins 1/3: the 5 V path reaches them around pin 1 "
        "(between it and the H1 hole) on both layers. Fine-pitch pins are entered with short necks (< 1.5 mm).",
        "",
        design_notes_markdown(pi, "5.1 V / 5 A Pi rail: U2 TPS568230", [
            ("UVLO", "VIN UVLO 4.2 typ / 4.4 V max rising, 3.8 V falling (datasheet)",
             "EN held at 3.3 V by R9 + D3 (EN abs. max 4 V); the internal 4.4 V UVLO sets start-up, so the rail survives "
             "2S sag to ~5.9 V (dropout) instead of the old 6.0 V UVLO"),
            ("Mode", "MODE divider 110 k / 51 k (Table 1)", "FCCM, 600 kHz"),
            ("Hold-up", "t = C (V0^2 - V1^2) / (2 P)", f"{hold * 1e6:.0f} us at 6.5 W from {pi.values['v_out_nominal']:.2f} V to "
             "the Pi's 4.63 V brown-out (220 uF polymer + ceramics); plus 220 uF on VIN_HAT"),
        ]),
        design_notes_markdown(servo, "6.0 V servo rail: U3 TPS56528", [
            ("Current limit", "valley I_ocl 5.5 / 6.2 / 7.8 A (min/typ/max, datasheet)",
             f"servo stall (2.5 A, catalog) is supplied; a shorted servo is limited to <= {servo.values['i_out_limit_max']:.1f} A"),
            ("Dropout", "Dmax = 1 - t_off(min) fsw = 1 - 310 ns x 650 kHz", f"{servo.ic.max_duty:.3f}: the servo sees "
             f"~{min(servo.values['v_out_nominal'], servo.ic.max_duty * 7.4 - 2.5 * 0.1):.2f} V from a nominal 2S pack"),
        ]),
        "## Protection and monitoring",
        "",
        "- Reverse polarity: DMP3013SFV P-MOSFET (-30 V, 9.5 mOhm at -10 V) in the + lead, gate pulled to GND by 100 k, "
        "BZT52B12 clamps VGS (VGS max +-25 V).",
        "- TVS: SMAJ16A (VRWM 16 V, VBR 17.8 V min, VC 26 V at 15.4 A). Its clamp exceeds the regulators' VIN abs. max "
        "(20/22 V) at full surge current (reported as a warning); a 2S-only build should fit an SMAJ10A.",
        "- INA226 at 0x40 (A0 = A1 = GND) across a 2 mOhm Vishay WSK2512 Kelvin shunt, 10 Ohm + 100 nF filter "
        "(SBOS547 sec. 8.4.1), sense traces from the shunt's Kelvin pads. VBUS measures VIN_HAT. Full scale 81.92 mV / "
        "2 mOhm = 41 A, LSB 1.25 mA. **Limitation:** the INA226 sees only the HAT branch (Pi, servo, logic). The ESC/motor "
        "current splits off in the XT60 Y-harness before the HAT and is not measured.",
        "- MPU-6050 at 0x68 (AD0 = GND), CLKIN/FSYNC low, REGOUT 100 nF, CPOUT 2.2 nF / 50 V, VDD/VLOGIC 100 nF / 10 nF.",
        "- I2C pull-ups 4.7 kOhm to 3V3 (parallel with the Pi's 1.8 kOhm: 1.3 kOhm, 2.6 mA sink).",
        "- 220 Ohm series resistors on the ESC (after the arbiter) and servo PWM lines; 10 kOhm encoder pull-up.",
        "- J_ESC pin 2 (the ESC's BEC) is not connected: the servo is powered only by U3.",
        "",
        "## Failsafe arbiter (U4 ATtiny412)",
        "",
        f"- The Pi's ESC PWM ({arb.input_pin}, GPIO18) reaches the ESC only through U4. The Pi toggles a heartbeat on "
        f"{arb.heartbeat_pin} (GPIO27) every control cycle.",
        f"- PASS: U4 mirrors every PWM edge (pin-change interrupt, ~{arb.latency_us:g} us latency, estimated).",
        f"- Timeout: no heartbeat edge for {arb.timeout * 1000:.0f} ms -> FAILSAFE: {arb.neutral_us:.0f} us neutral pulses every "
        f"{arb.frame * 1000:.0f} ms; red LED D4 on. Worst-case latency from the last edge to the first neutral frame is "
        f"{(arb.timeout + arb.frame) * 1000:.0f} ms.",
        f"- Re-arm: {arb.rearm_edges} heartbeat edges within the timeout and a commanded pulse within +-{arb.rearm_band_us:g} us "
        "of neutral. U4 boots in FAILSAFE.",
        "- U4 runs from the Pi's 3V3; if the Pi is unpowered, R15 holds ESC_PWM low and the ESC's own signal-loss failsafe "
        "applies. UPDI header J8 programs U4. Behaviour model: `r3_kicad.arbiter.FailsafeArbiter`.",
        "",
        "## Mounting",
        "",
        f"- Four M2.5 holes on the HAT pattern, attached with {intent.mounting.screw}s (head "
        f"{intent.mounting.head_diameter:g} x {intent.mounting.head_height:g} mm) on top and the Pi stack's "
        f"{intent.mounting.standoff} below.",
        f"- KiCad rule areas on each hole footprint: no parts within {intent.mounting.top_part_radius:.2f} mm on top "
        f"(head + {intent.mounting.print_clearance:g} mm FDM clearance for a printed cap, bore "
        f"{intent.mounting.cap_inner_diameter:.1f} mm) or {intent.mounting.bottom_part_radius:.2f} mm below (standoff "
        f"across corners); no copper within the metal contact circles ({intent.mounting.top_copper_radius:.2f} / "
        f"{intent.mounting.bottom_copper_radius:.2f} mm). DRC enforces both; `board.json` `mounting` hands the "
        "envelopes to CAD. KiCad reports `lib_footprint_mismatch` (warning) on H1-H4 because of these areas.",
        "- The Pi's 5 V pins sit between H1 and the header, so the 5 V path passes the standoff contact circle "
        "through a 0.7 mm neck on both layers (reported by `pcb_trace_over_ipc2152`).",
        "",
        "## Back-powering",
        "",
        "U2 drives the Pi's 5 V pins directly. Do not connect the Pi's USB-C supply at the same time (no ideal-diode "
        "OR-ing); the Pi 5 needs `usb_max_current_enable=1` for 5 A GPIO-supplied operation.",
        "",
    ]
    if intent.notes:
        lines += ["## Notes", ""] + [f"- {n}" for n in intent.notes] + [""]
    return "\n".join(lines)
